/*
 * Verifies the hand-written FFI layouts in src/ffi.rs against the official WDK headers.
 * Every value here is also asserted on the Rust side; a mismatch fails either build.
 * Syntax-check only (nothing is emitted):
 *   cl /nologo /Zs /kernel /W4 /WX /I<WDK>\km /I<WDK>\shared layout_check.c
 */
#define NDIS630 1
#include <ntddk.h>
#include <wdmsec.h>
#pragma warning(push)
#pragma warning(disable : 4201 4324)
#include <ndis.h>
#include <fwpsk.h>
#pragma warning(pop)

