C_ASSERT(sizeof(GUID) == 16);
C_ASSERT(sizeof(KEVENT) == 24);
C_ASSERT(sizeof(KSPIN_LOCK) == 8);

C_ASSERT(FIELD_OFFSET(DRIVER_OBJECT, DriverUnload) == 104);
C_ASSERT(FIELD_OFFSET(DRIVER_OBJECT, MajorFunction) == 112);
C_ASSERT(sizeof(DRIVER_OBJECT) == 336);
C_ASSERT(IRP_MJ_CREATE == 0 && IRP_MJ_CLOSE == 2 && IRP_MJ_DEVICE_CONTROL == 14);

C_ASSERT(FIELD_OFFSET(IRP, AssociatedIrp.SystemBuffer) == 0x18);
C_ASSERT(FIELD_OFFSET(IRP, IoStatus.Status) == 0x30);
C_ASSERT(FIELD_OFFSET(IRP, IoStatus.Information) == 0x38);
C_ASSERT(FIELD_OFFSET(IRP, Tail.Overlay.CurrentStackLocation) == 0xB8);

C_ASSERT(FIELD_OFFSET(IO_STACK_LOCATION, Parameters.DeviceIoControl.OutputBufferLength) == 8);
C_ASSERT(FIELD_OFFSET(IO_STACK_LOCATION, Parameters.DeviceIoControl.InputBufferLength) == 16);
C_ASSERT(FIELD_OFFSET(IO_STACK_LOCATION, Parameters.DeviceIoControl.IoControlCode) == 24);

C_ASSERT(sizeof(FWP_VALUE0) == 16 && FIELD_OFFSET(FWP_VALUE0, uint32) == 8);
C_ASSERT(sizeof(FWP_BYTE_BLOB) == 16 && FIELD_OFFSET(FWP_BYTE_BLOB, data) == 8);
C_ASSERT(FWP_UINT8 == 1 && FWP_UINT16 == 2 && FWP_UINT32 == 3);
C_ASSERT(FWP_BYTE_ARRAY16_TYPE == 11 && FWP_BYTE_BLOB_TYPE == 12);

C_ASSERT(sizeof(FWPS_INCOMING_VALUE0) == 16);
C_ASSERT(FIELD_OFFSET(FWPS_INCOMING_VALUES0, valueCount) == 4);
C_ASSERT(FIELD_OFFSET(FWPS_INCOMING_VALUES0, incomingValue) == 8);
C_ASSERT(sizeof(FWPS_INCOMING_VALUES0) == 16);

C_ASSERT(FIELD_OFFSET(FWPS_INCOMING_METADATA_VALUES0, currentMetadataValues) == 0);
C_ASSERT(FIELD_OFFSET(FWPS_INCOMING_METADATA_VALUES0, flowHandle) == 32);
C_ASSERT(FIELD_OFFSET(FWPS_INCOMING_METADATA_VALUES0, processPath) == 48);
C_ASSERT(FIELD_OFFSET(FWPS_INCOMING_METADATA_VALUES0, processId) == 64);
C_ASSERT(FWPS_METADATA_FIELD_FLOW_HANDLE == 0x2);
C_ASSERT(FWPS_METADATA_FIELD_PROCESS_PATH == 0x8);
C_ASSERT(FWPS_METADATA_FIELD_PROCESS_ID == 0x20);

C_ASSERT(FIELD_OFFSET(FWPS_CLASSIFY_OUT0, actionType) == 0);
C_ASSERT(FIELD_OFFSET(FWPS_CLASSIFY_OUT0, rights) == 24);
C_ASSERT(sizeof(FWPS_CLASSIFY_OUT0) == 40);
C_ASSERT(FWP_ACTION_CONTINUE == 0x2006 && FWPS_RIGHT_ACTION_WRITE == 1);

C_ASSERT(FIELD_OFFSET(FWPS_STREAM_DATA0, dataLength) == 48);
C_ASSERT(sizeof(FWPS_STREAM_DATA0) == 64);
C_ASSERT(FWPS_STREAM_FLAG_RECEIVE == 0x1);
C_ASSERT(FIELD_OFFSET(FWPS_STREAM_CALLOUT_IO_PACKET0, missedBytes) == 8);
C_ASSERT(FIELD_OFFSET(FWPS_STREAM_CALLOUT_IO_PACKET0, countBytesRequired) == 16);
C_ASSERT(FIELD_OFFSET(FWPS_STREAM_CALLOUT_IO_PACKET0, countBytesEnforced) == 24);
C_ASSERT(FIELD_OFFSET(FWPS_STREAM_CALLOUT_IO_PACKET0, streamAction) == 32);
C_ASSERT(sizeof(FWPS_STREAM_CALLOUT_IO_PACKET0) == 40);
C_ASSERT(FWPS_STREAM_ACTION_NONE == 0);

C_ASSERT(FIELD_OFFSET(FWPS_CALLOUT0, flags) == 16);
C_ASSERT(FIELD_OFFSET(FWPS_CALLOUT0, classifyFn) == 24);
C_ASSERT(FIELD_OFFSET(FWPS_CALLOUT0, notifyFn) == 32);
C_ASSERT(FIELD_OFFSET(FWPS_CALLOUT0, flowDeleteFn) == 40);
C_ASSERT(sizeof(FWPS_CALLOUT0) == 48);

C_ASSERT(FWPS_FIELD_ALE_FLOW_ESTABLISHED_V4_ALE_APP_ID == 0);
C_ASSERT(FWPS_FIELD_ALE_FLOW_ESTABLISHED_V4_IP_LOCAL_ADDRESS == 2);
